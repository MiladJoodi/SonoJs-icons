const cryptoRank = new Map<string, number>(
  CRYPTO_POPULARITY_ORDER.map((id, i) => [id, i]),
);
const devRank = new Map<string, number>(
  DEV_POPULARITY_ORDER.map((id, i) => [id, i]),
);

/** Lower = more popular. Unlisted icons get a large rank (sort after). */
export function packPopularityRank(
  groupId: string,
  iconId: string,
): number {
  if (groupId === "crypto") {
    return cryptoRank.get(iconId) ?? Number.MAX_SAFE_INTEGER;
  }
  if (groupId === "dev") {
    return devRank.get(iconId) ?? Number.MAX_SAFE_INTEGER;
  }
  return Number.MAX_SAFE_INTEGER;
}
