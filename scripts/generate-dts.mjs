/**
 * Emit clean .d.ts for IDE autocomplete.
 * tsup's rollup-dts mangles named exports (`A as FooIcon`) which breaks IntelliSense.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const generated = join(root, "src", "generated");

function collectIconNames() {
  /** @type {Set<string>} */
  const names = new Set();
  if (!existsSync(generated)) return [];

  const sources = readdirSync(generated, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name);

  for (const source of sources) {
    const iconsDir = join(generated, source, "icons");
    let files = [];
    try {
      files = readdirSync(iconsDir);
    } catch {
      continue;
    }
    for (const file of files) {
      if (!/\.(tsx|ts)$/.test(file)) continue;
      const text = readFileSync(join(iconsDir, file), "utf8");
      for (const m of text.matchAll(/export const (\w+Icon)\b/g)) {
        names.add(m[1]);
      }
    }
  }
  return [...names].sort((a, b) => a.localeCompare(b));
}

const iconNames = collectIconNames();

mkdirSync(dist, { recursive: true });

const iconDecls = iconNames
  .map((name) => `export declare const ${name}: IconComponent;`)
  .join("\n");

const namedIconsDts = `/* Auto-generated by scripts/generate-dts.mjs - do not edit. */
import type { ForwardRefExoticComponent, RefAttributes } from "react";
import type { IconProps } from "./index";

type IconComponent = ForwardRefExoticComponent<
  Omit<IconProps, "ref"> & RefAttributes<SVGSVGElement>
>;

${iconDecls || "export {};"}
`;

writeFileSync(join(dist, "named-icons.d.ts"), namedIconsDts);

