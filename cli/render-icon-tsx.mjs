/**
 * Build a self-contained React TSX icon component (no @sonojs/icons runtime dependency).
 * @param {{
 *   componentName: string,
 *   color: { viewBox: string, body: string },
 * }} icon
 */
export function renderIconTsx(icon) {
  const { componentName, color } = icon;
  const colorVb = JSON.stringify(color.viewBox);
  const colorBody = JSON.stringify(color.body);

  return `/* Generated by @sonojs/icons - self-contained icon. */
import {
  forwardRef,
  useId,
  useMemo,
  type CSSProperties,
  type Ref,
  type SVGProps,
} from "react";

export type ${componentName}Props = Omit<
  SVGProps<SVGSVGElement>,
  "width" | "height" | "viewBox" | "color"
> & {
  size?: number | string;
  width?: number | string;
  height?: number | string;
  title?: string;
  style?: CSSProperties;
};

const VIEW_BOX = ${colorVb};
const BODY = ${colorBody};

function parseViewBox(viewBox: string) {
  const parts = viewBox.trim().split(/[\\s,]+/).map(Number);
  if (parts.length !== 4 || parts.some((n) => Number.isNaN(n))) {
    return { width: 24, height: 24 };
  }
  return { width: parts[2]!, height: parts[3]! };
}

function resolveDimensions(
  props: ${componentName}Props,
  viewBox: string,
): { width: number | string; height: number | string } {
  const { width: vbW, height: vbH } = parseViewBox(viewBox);
  const ratio = vbW / vbH || 1;
  if (props.width != null && props.height != null) {
    return { width: props.width, height: props.height };
  }
  if (props.width != null) {
    const w =
      typeof props.width === "number"
        ? props.width
        : Number.parseFloat(String(props.width));
    if (!Number.isNaN(w)) return { width: props.width, height: w / ratio };
    return { width: props.width, height: props.height ?? props.size ?? vbH };
  }
  if (props.height != null) {
    const h =
      typeof props.height === "number"
        ? props.height
        : Number.parseFloat(String(props.height));
    if (!Number.isNaN(h)) return { width: h * ratio, height: props.height };
    return { width: props.width ?? props.size ?? vbW, height: props.height };
  }
  const size = props.size ?? 24;
  return { width: size, height: size };
}

function scopeMarkup(markup: string, scope: string) {
  return markup
    .replace(/\\bid=(["'])([^"']+)\\1/gi, (_m, q, id) => \`id=\${q}\${scope}\${id}\${q}\`)
    .replace(/url\\((["']?)#([^"')]+)\\1\\)/gi, (_m, q, id) => \`url(\${q}#\${scope}\${id}\${q})\`)
    .replace(
      /xlink:href=(["'])#([^"']+)\\1/gi,
      (_m, q, id) => \`xlink:href=\${q}#\${scope}\${id}\${q}\`,
    );
}

export const ${componentName} = forwardRef(function ${componentName}(
  props: ${componentName}Props,
  ref: Ref<SVGSVGElement>,
) {
  const {
    size: _size,
    title,
    className,
    style,
    width: _width,
    height: _height,
    ...rest
  } = props;

  const { width, height } = resolveDimensions(props, VIEW_BOX);
  const isDecorative = title == null || title === "";
  const scope = \`sono-\${useId().replace(/:/g, "")}-\`;
  const scoped = useMemo(() => scopeMarkup(BODY, scope), [scope]);

  return (
    <svg
      ref={ref}
      xmlns="http://www.w3.org/2000/svg"
      viewBox={VIEW_BOX}
      width={width}
      height={height}
      preserveAspectRatio="xMidYMid meet"
      className={className}
      style={style}
      role={isDecorative ? undefined : "img"}
      aria-label={isDecorative ? undefined : title}
      aria-hidden={isDecorative ? true : undefined}
      focusable="false"
      {...rest}
    >
      {title ? <title>{title}</title> : null}
      <g dangerouslySetInnerHTML={{ __html: scoped }} />
    </svg>
  );
});

${componentName}.displayName = ${JSON.stringify(componentName)};
`;
}
